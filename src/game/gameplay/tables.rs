#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_have_their_documented_shape() {
        for (n, &t) in TRIANGLE.iter().enumerate() {
            assert_eq!(usize::from(t), n * (n + 1) / 2);
        }
        // The largest index used: triangle 15 plus a minor axis of 14.
        assert!(usize::from(TRIANGLE[15]) + 14 < ATAN.len());
        assert_eq!(SIN[0x47], 0x7E);
        assert_eq!(SIN[0x79], 0x15);
    }
}
